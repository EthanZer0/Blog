import assert from 'node:assert/strict';
import { load } from 'cheerio';
import config from '../astro.config.mjs';
const renderer = await config.markdown.processor.createRenderer({syntaxHighlight:config.markdown.syntaxHighlight});
const markdown = ['## Heading','','![Caption](/avatar.png)','','| A | B |','| - | - |','| 1 | 2 |','','```typescript filename="hello.ts" expand','const answer = 42; // [!code highlight]','```','','$$','a^2+b^2=c^2','$$','','A footnote.[^a]','','[^a]: Detail.','',':::gallery','![one](/avatar.png)','![!two](/avatar.png)',':::'].join('\n');
const { code } = await renderer.render(markdown);
const $ = load(code);
assert.equal($('h2.group > span').text(),'Heading');
assert.equal($('h2 .heading-anchor i').length,1);
assert.equal($('p > figure').length,0);
assert.equal($('figure figcaption').first().text(),'Caption');
assert.equal($('img').first().attr('src'),`${(process.env.BASE_PATH || '/').replace(/\/$/,'')}/avatar.png`);
assert.ok($('table').parent().hasClass('overflow-auto'));
assert.equal($('[data-code-filename]').attr('data-code-filename'),'hello.ts');
assert.equal($('[data-code-expand]').length,1);
assert.equal($('[data-shiro-code] svg').length,1);
assert.equal($('[data-shiro-code] .highlighted').length,1);
assert.equal($('.katex-display').length,1);
assert.equal($('[data-shiro-code]').length,1);
assert.equal($('#md-footnote > ul').length,1);
assert.equal($('[data-gallery] .gallery-child').length,2);
assert.equal($('[data-gallery-step]').length,2);
assert.equal($('[data-gallery-index]').length,2);
const extended=load((await renderer.render(['::: grid {cols=3,gap=4}','![one](/avatar.png)','','![two](/avatar.png)',':::','','::: banner {error}','Message',':::','','||secret||','','<Tabs>','<tab label="One">','First','</tab>','<tab label="Two">','Second','</tab>','</Tabs>','','<tag>Label</tag>','','![Video](/movie.mp4)'].join('\n'))).code);
assert.match(extended('.relative.grid').attr('style'),/repeat\(3,/);
assert.match(extended('.relative.grid').attr('style'),/gap:4px/);
assert.equal(extended('[data-tabs] [data-tab-label]').length,2);
assert.equal(extended('.spoiler').text(),'secret');
assert.equal(extended('[data-markdown-tag]').text(),'Label');
assert.equal(extended('video[data-video-player]').length,1);
assert.equal(extended('.bg-red-50').length,1);
console.log('Verified extended Shiro container syntax, grid parameters, banner, Tabs, spoiler, tag and video.');
console.log('Verified Markdown headings, image captions, base URLs, table overflow, code filenames/icons/highlights/expand, footnotes and gallery structure.');
